"""Small helpers for the Pro Tips reading experience.

The article body is sanitized before it reaches these helpers, so any HTML we
add here (heading ids) is generated by us and is safe to render.
"""

from __future__ import annotations

import re
from html import unescape

from django.utils.text import slugify

_HEADING_RE = re.compile(
    r"<(?P<tag>h[23])(?P<attrs>[^>]*)>(?P<text>.*?)</(?P=tag)>",
    re.IGNORECASE | re.DOTALL,
)
_TAG_RE = re.compile(r"<[^>]+>")
_TOC_RE = re.compile(
    r'<h(?P<level>[23])\s+id="(?P<id>[^"]+)"[^>]*>(?P<text>.*?)</h(?P=level)>',
    re.IGNORECASE | re.DOTALL,
)


def _plain_text(value: str) -> str:
    return " ".join(unescape(_TAG_RE.sub(" ", value)).split())


def add_heading_ids(html: str) -> str:
    """Give every H2/H3 a stable id so the table of contents can link to it."""

    if not html:
        return ""

    used: set[str] = set()

    def replace(match: re.Match) -> str:
        tag = match.group("tag")
        attrs = match.group("attrs")
        text = match.group("text")
        base = slugify(_plain_text(text))[:64] or "section"
        candidate = base
        suffix = 2
        while candidate in used:
            candidate = f"{base}-{suffix}"
            suffix += 1
        used.add(candidate)
        attrs = attrs.replace(' id="', ' data-old-id="')
        return f'<{tag} id="{candidate}"{attrs}>{text}</{tag}>'

    return _HEADING_RE.sub(replace, html)


def extract_toc(html: str) -> list[dict]:
    """Return ``[{id, text, level}]`` for the headings in an article."""

    if not html:
        return []

    items = []
    for match in _TOC_RE.finditer(html):
        text = _plain_text(match.group("text"))
        if not text:
            continue
        items.append(
            {
                "id": match.group("id"),
                "text": text,
                "level": int(match.group("level")),
            }
        )
    return items
